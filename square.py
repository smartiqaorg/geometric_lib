def area(a):
    '''
    Calculates the area of a square.

    Parameters:
        a (int/float): The side length of the square.

    Returns:
        int/float: The area of the square.

    Example:
        >>> area(5)
        25
    '''
    return a * a

def perimeter(a):
    '''
    Calculates the perimeter of a square.

    Parameters:
        a (int/float): The side length of the square.

    Returns:
        int/float: The perimeter of the square.

    Example:
        >>> perimeter(5)
        20
    '''
    return 4 * a
