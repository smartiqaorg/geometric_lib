def area(a, h):
    """
    Вычисляет площадь треугольника по основанию и высоте.

    Параметры:
        a (float): длина основания треугольника.
        h (float): высота, проведённая к основанию.

    Возвращает:
        float: площадь треугольника.

    Пример:
        area(6, 4) -> 12.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """
    Вычисляет периметр треугольника по длинам трёх сторон.

    Параметры:
        a (float): первая сторона.
        b (float): вторая сторона.
        c (float): третья сторона.

    Возвращает:
        float: периметр треугольника.

    Пример:
        perimeter(3, 4, 5) -> 12
    """
    return a + b + c