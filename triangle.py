    '''
    Вычисляет периметр треугольника с заданными сторонами.

    Ввод: a (float) - сторона 1, b (float) - сторона 2, c (float) - сторона 3
    Вывод: perimiter (float) - периметр

    Пример использования:
    perimiter(3,4,5) = 12
    '''
