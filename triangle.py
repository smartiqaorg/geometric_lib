def area(a, h):
    '''
    Возвращает площадь треугольника.

    :param a: сторона, к которой проведена высота (float)
    :param h: высота, опущенная на сторону a (float)
    :return: площадь треугольника (float)

    Формула: S = (a · h) / 2

    Пример:
        >>> area(10.0, 5.0)
        25.0
    '''
    return (a * h) / 2


def perimeter(a, b, c):
    '''
    Возвращает периметр треугольника.

    :param a: первая сторона (float)
    :param b: вторая сторона (float)
    :param c: третья сторона (float)
    :return: периметр треугольника (float)

    Формула: P = a + b + c

    Пример:
        >>> perimeter(3.0, 4.0, 5.0)
        12.0
    '''
    return a + b + c